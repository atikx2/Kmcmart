#!/usr/bin/env node
/** Generate a reviewable SQL import from Kmc Bazar. Usage: node scripts/import-kmcbazar.mjs > /tmp/kmcbazar-products.sql */
const SOURCE = 'http://kmcbazar.com';
const categories = [
  ['accessories', 'Accessories', 'accessories'],
  ['home-&-kitchen', 'Home & Kitchen', 'home-kitchen'],
  ['gadget-items', 'Gadget items', 'electronics'],
  ['food-suppliment', 'Food Suppliment', 'food-suppliment'],
  ['health', 'Health', 'health'],
  ['bathroom-items', 'Bathroom Items', 'bathroom-items'],
  ['cosmetics', 'Cosmetics', 'cosmetics'],
];
const esc = (s) => String(s ?? '').replace(/'/g, "''");
const htmlText = (s) => String(s).replace(/<[^>]+>/g, ' ').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/\s+/g, ' ').trim();
const prices = (s) => [...s.matchAll(/৳\s*([\d,]+)/g)].map(m => Number(m[1].replace(/,/g, ''))).filter(Number.isFinite);
async function get(url) { const r = await fetch(url, { headers: { 'User-Agent': 'Kmcmart authorised catalogue importer' } }); if (!r.ok) throw new Error(`${r.status} ${url}`); return r.text(); }
function links(page) { return [...page.matchAll(/href=["'](?:https?:\/\/kmcbazar\.com)?\/product\/([^"']+)["']/gi)].map(m => decodeURIComponent(m[1].split(/[?#]/)[0])).filter((x,i,a)=>x && a.indexOf(x)===i); }
function meta(page, key) { const r = new RegExp(`<meta[^>]+(?:property|name)=["']${key}["'][^>]+content=["']([^"']*)["']`, 'i').exec(page); return r ? htmlText(r[1]) : ''; }
function image(page) { return meta(page,'og:image') || (/class=["'][^"']*(?:product|gallery)[^"']*["'][^>]*>[\s\S]{0,500}?src=["']([^"']+)["']/i.exec(page)?.[1] || /<img[^>]+src=["']([^"']+)["']/i.exec(page)?.[1] || ''); }
function name(page, slug) { return meta(page,'og:title') || htmlText(/<h1[^>]*>([\s\S]*?)<\/h1>/i.exec(page)?.[1] || slug.replace(/-\d+$/, '').replace(/-/g,' ')); }
function sqlValue(v) { return `'${esc(v)}'`; }
const main = async () => {
  const all = new Map();
  for (const [sourceSlug, categoryName, targetSlug] of categories) {
    let page; try { page = await get(`${SOURCE}/category/${sourceSlug}`); } catch (e) { console.error(`Skipping ${sourceSlug}: ${e.message}`); continue; }
    for (const slug of links(page)) all.set(slug, { slug, categoryName, targetSlug });
  }
  const rows = [];
  for (const item of all.values()) {
    try {
      const page = await get(`${SOURCE}/product/${item.slug}`);
      const ps = prices(page); const sell = ps[0] || 0; const regular = ps[1] || sell;
      if (!sell) continue;
      const img = image(page); const imageUrl = img.startsWith('http') ? img : `${SOURCE}${img.startsWith('/') ? '' : '/'}${img}`;
      rows.push(`(${sqlValue(name(page,item.slug))}, ${sqlValue(item.slug)}, (SELECT id FROM categories WHERE slug=${sqlValue(item.targetSlug)}), '', ${JSON.stringify([imageUrl])}::jsonb, ${regular}, ${sell}, ${Math.max(0,sell-200)}, 50, true, true)`);
      process.stderr.write(`Collected ${rows.length}: ${item.slug}\n`);
    } catch (e) { process.stderr.write(`Skipped ${item.slug}: ${e.message}\n`); }
  }
  console.log('-- Generated by scripts/import-kmcbazar.mjs');
  console.log('-- Review before running. Purchase price = selling price - 200, minimum 0.');
  console.log('BEGIN;');
  if (rows.length) console.log(`INSERT INTO products (name, slug, category_id, description, images, regular_price, sell_price, cost_price, stock, free_delivery, is_active) VALUES\n${rows.join(',\n')}\nON CONFLICT (slug) DO NOTHING;`);
  console.log('COMMIT;');
  console.error(`Generated ${rows.length} product rows.`);
};
main().catch(e => { console.error(e); process.exit(1); });
